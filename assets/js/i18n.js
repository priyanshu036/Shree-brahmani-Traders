  /* Subscribe to language changes. Returns an unsubscribe function. */
  I18N.on = function (fn) {
    if (typeof fn !== "function") return function () {};
    listeners.push(fn);
    return function () {
      const i = listeners.indexOf(fn);
      if (i !== -1) listeners.splice(i, 1);
    };
  };

