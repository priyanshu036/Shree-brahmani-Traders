  /* Change language, persist, notify listeners. */
  I18N.setLang = function (lang) {
    const next = normalizeLang(lang);
    if (next === current) return current;
    current = next;
    try {
      localStorage.setItem(STORAGE_KEY, current);
    } catch (e) { /* ignore */ }
    syncHtmlLang();
    listeners.slice().forEach(function (fn) {
      try { fn(current); } catch (e) { /* keep other listeners alive */ }
    });
    try {
      document.dispatchEvent(new CustomEvent("sbt:langchange", { detail: { lang: current } }));
    } catch (e) { /* ignore */ }
    return current;
  };

