  /* Translate a key. Supports {placeholder} interpolation. */
  I18N.t = function (key, vars) {
    if (key === null || key === undefined) return "";
    const table = DICT[current] || DICT[DEFAULT_LANG];
    let text = table[key];
    if (text === undefined) text = DICT[DEFAULT_LANG][key];
    if (text === undefined) return String(key);
    if (vars) {
      text = text.replace(/\{(\w+)\}/g, function (match, name) {
        return vars[name] === undefined || vars[name] === null ? match : String(vars[name]);
      });
    }
    return text;
  };

